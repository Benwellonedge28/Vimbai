"""Writes catalog/ from the gateway's route table plus the manifest's ownership map.

services.json says what the gateway routes today; the manifest says who owns each service. Neither
is enough alone: the catalogue needs both, per service, in one place a validator can read.

The catalogue is generated for the same reason the manifest is. A hand-written catalogue is a
second inventory, and the repository has already been confused once by three counts of the same
estate. tests/test_catalog.py fails if these files stop matching the generator.

Run after adding, retiring or reassigning a service.
"""

import importlib.util
import os
import re

import yaml

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(REPO, "catalog")
SERVICES_DIR = os.path.join(OUT_DIR, "services")


def _manifest():
    path = os.path.join(REPO, "scripts", "migration_manifest.py")
    spec = importlib.util.spec_from_file_location("migration_manifest", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


MANIFEST = _manifest()


def _endpoints(name):
    """The routes a service answers, read from its own main.py."""
    path = os.path.join(REPO, name, "main.py")
    if not os.path.isfile(path):
        return []
    with open(path, encoding="utf-8") as handle:
        text = handle.read()
    pairs = re.findall(r'@app\.(get|post|put|delete|patch)\("([^"]+)"', text)
    return [f"{method.upper()} {route}" for method, route in pairs]


def entries():
    """One record per routed service, in the order the gateway lists them."""
    ported = MANIFEST.ported_names()
    rows = []
    for service in MANIFEST.routed():
        name = service["name"]
        domain = MANIFEST.OWNERS.get(name, "")
        _, owns_records = MANIFEST.shape(name)
        rows.append(
            {
                "name": name,
                "domain": domain,
                "target": MANIFEST.DOMAINS.get(domain, ("", ""))[1],
                "port": service.get("port"),
                "gateway_path": service.get("path"),
                "auth_required": bool(service.get("auth_required")),
                "engine": "rust" if name in ported else "python",
                "records": owns_records,
                "endpoints": _endpoints(name),
            }
        )
    return rows


def _dump(document):
    return yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=100)


def catalog_text(rows=None):
    rows = entries() if rows is None else rows
    document = {
        "catalog": {
            "version": 1,
            "generated_by": "scripts/generate_catalog.py",
            "authority": "gateway/go/config/services.json for routes, scripts/migration_manifest.py for ownership",
            "services": len(rows),
        },
        "domains": [
            {"name": name, "responsibility": description, "target": target}
            for name, (description, target) in MANIFEST.DOMAINS.items()
        ],
        "services": rows,
    }
    return "# Generated by scripts/generate_catalog.py. Do not edit by hand.\n" + _dump(document)


def domain_texts(rows=None):
    rows = entries() if rows is None else rows
    by_domain = {}
    for row in rows:
        by_domain.setdefault(row["domain"] or "unassigned", []).append(row)
    texts = {}
    for domain, services in sorted(by_domain.items()):
        description, target = MANIFEST.DOMAINS.get(domain, ("unowned", ""))
        document = {
            "domain": {
                "name": domain,
                "responsibility": description,
                "target": target,
                "services": len(services),
            },
            "services": services,
        }
        texts[domain] = "# Generated by scripts/generate_catalog.py. Do not edit by hand.\n" + _dump(document)
    return texts


README = """# Catalogue

The one place the estate is described: every service the gateway routes, the domain that owns it,
where that domain's code lives, and what each service answers.

Generated by `scripts/generate_catalog.py` from two sources of truth that already existed:

* `gateway/go/config/services.json` - the routes the gateway actually serves.
* `scripts/migration_manifest.py` - which domain owns each service.

Nothing here is typed by hand, and `tests/test_catalog.py` fails if these files drift from the
generator. That matters more than it sounds: this repository has already had three different counts
of the same services, and a catalogue that can disagree with the router is worse than none.

## Files

```
catalog/services/catalog.yaml      every service, in gateway order
catalog/services/<domain>.yaml     the same services grouped by owner
```

Each entry carries the port, the gateway path, whether authentication is required, how many
endpoints the service answers, whether it still owns records, and whether its figures already come
from a Rust engine. The `target` field is where the domain lands in the Rust workspace.

## What this is not

It is not an API contract. The paths are the ones each Python service declares today; the contracts
under `contracts/` are the versioned, agreed shape, and they do not exist yet.

It is not a deployment plan either. `engine` says where the arithmetic runs, not what should be
deployed separately.
"""


def main():
    os.makedirs(SERVICES_DIR, exist_ok=True)
    rows = entries()
    with open(os.path.join(SERVICES_DIR, "catalog.yaml"), "w", encoding="utf-8") as handle:
        handle.write(catalog_text(rows))
    for domain, text in domain_texts(rows).items():
        with open(os.path.join(SERVICES_DIR, f"{domain}.yaml"), "w", encoding="utf-8") as handle:
            handle.write(text)
    with open(os.path.join(OUT_DIR, "README.md"), "w", encoding="utf-8") as handle:
        handle.write(README)
    unowned = [row["name"] for row in rows if not row["domain"]]
    print(f"wrote catalog: {len(rows)} services across {len(domain_texts(rows))} domains")
    if unowned:
        print("unowned: " + ", ".join(unowned))


if __name__ == "__main__":
    main()
