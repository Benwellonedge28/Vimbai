"""Writes docs/RUST-MIGRATION-BACKLOG.md from the gateway's own route table.

The point is that the backlog cannot be guessed at or remembered wrong: it is derived from
gateway/go/config/services.json, and a service counts as ported only when
rust/CALCULATOR-PORT.md names it (the ported crates) or its main.py loads the native
wheel. Everything else is Python-only work, split by whether it owns records, because that
decides whether the port can be a pure function or needs vimbai_store.

Rerun after registering, porting or deleting a service:

    python3 scripts/migration_backlog.py
"""

import importlib.util
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "gateway" / "go" / "config" / "services.json"
PORT_MAP = ROOT / "rust" / "CALCULATOR-PORT.md"

# The port tracker is read one way, in one place. The manifest's reader takes only the bullets under
# "Wired to the Rust library", which is the list of services actually served from Rust; the other
# sections list services that are not. Matching the name anywhere in the file counted both, and even
# matched `currency-service` inside `multi-currency-service`.
_spec = importlib.util.spec_from_file_location("migration_manifest", ROOT / "scripts" / "migration_manifest.py")
MANIFEST = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(MANIFEST)
OUT = ROOT / "docs" / "RUST-MIGRATION-BACKLOG.md"
PERSISTENCE = re.compile(r"neo4j|AsyncSession|crud\.|sqlite3")


def survey():
    services = json.loads(REGISTRY.read_text())["services"]
    manifest_ported = MANIFEST.ported_names()
    rows = []
    for service in services:
        name = service["name"]
        directory = ROOT / name
        if not directory.is_dir():
            continue
        main = (directory / "main.py").read_text()
        endpoints = re.findall(r'@app\.(?:get|post|put|delete|patch)\("([^"]+)"', main)
        ported = name in manifest_ported
        engine = "native seam" if "vimbai_native" in main else ("rust http" if ported else "none")
        rows.append(
            {
                "name": name,
                "port": service["port"],
                "endpoints": len(endpoints),
                "owns_records": bool(PERSISTENCE.search(main)),
                "rust_engine": engine,
                "lines": len(main.splitlines()),
            }
        )
    return rows


def table(title, rows):
    out = ["### " + title, "", "%d services." % len(rows), "", "```"]
    for row in rows:
        out.append(
            "%-46s %-5s routes=%-3s records=%-3s %s"
            % (
                row["name"],
                row["port"],
                row["endpoints"],
                "yes" if row["owns_records"] else "no",
                row["rust_engine"],
            )
        )
    out += ["```", ""]
    return out


def render(rows):
    ported = [r for r in rows if r["rust_engine"] != "none"]
    backlog = sorted(
        (r for r in rows if r["rust_engine"] == "none"),
        key=lambda r: (r["owns_records"], r["lines"], r["name"]),
    )
    pure = [r for r in backlog if not r["owns_records"]]
    owning = [r for r in backlog if r["owns_records"]]
    out = [
        "# Rust migration backlog",
        "",
        "Generated by `scripts/migration_backlog.py`. Every service the gateway routes appears",
        "exactly once here: either proven on a Rust engine, or on the backlog with its size and",
        "whether it owns records. `tests/test_migration_backlog.py` fails if this drifts.",
        "",
        "## Where things stand",
        "",
        "The gateway routes %d services. %d are proven on a Rust engine. %d are still Python-only."
        % (len(rows), len(ported), len(backlog)),
        "",
        "Of the backlog, %d own no records and can be ported as pure functions; %d own records and"
        % (len(pure), len(owning)),
        "need vimbai_store alongside the maths.",
        "",
    ]
    out += table("Already on a Rust engine", ported)
    out += table("Backlog: no records owned (port the maths only)", pure)
    out += table("Backlog: owns records (needs vimbai_store)", owning)
    return "\n".join(out) + "\n", len(rows), len(ported), len(backlog)


if __name__ == "__main__":
    rows = survey()
    text, routed, ported, pending = render(rows)
    OUT.write_text(text)
    print("wrote %s: %d routed, %d on rust, %d python only" % (OUT.name, routed, ported, pending))
