#!/usr/bin/env python3
"""Write docs/MIGRATION-MAP.md: every routed service, where it lives now, where it goes, and what retires it.

The target architecture asks for an exhaustive migration manifest: every service directory mapped to its exact
destination, with its API ownership, data ownership, verification and retirement criteria. That is what this writes,
straight from the generated catalogue, so the map can never drift from the routes and the ownership that are actually in
force.

Run after generate_catalog.py:

    python3 scripts/generate_catalog.py && python3 scripts/migration_map.py

Deliberately generated: hand-editing the output would let it disagree with the catalogue, which is the failure this file
exists to prevent.
"""

from __future__ import annotations

import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
CATALOGUE = ROOT / "catalog" / "services" / "catalog.yaml"
OUTPUT = ROOT / "docs" / "MIGRATION-MAP.md"

# Where a ported service is proven, so a reader can go and check rather than take the word for it.
PROOF = {
    "rust": "crate tests + HTTP route test in rust/apps/api-server/tests",
    "python": "the Python service's own suite, still the only proof",
}


def gate(engine: str, records: bool) -> str:
    """What has to be true before this service's Python directory stops answering."""
    if engine != "rust":
        return "port the crate, register each fixed path once, add its route test"
    if records:
        return "parity on record shapes and Book scoping, then de-register from services.json, k8s and CI"
    return "parity on every calculator output, then de-register from services.json, k8s and CI"


def main() -> None:
    catalog = yaml.safe_load(CATALOGUE.read_text())
    services = catalog["services"]
    domains = {domain["name"]: domain for domain in catalog["domains"]}

    on_rust = [service for service in services if service["engine"] == "rust"]
    on_python = [service for service in services if service["engine"] != "rust"]

    lines: list[str] = []
    lines.append("# Vimbai migration map")
    lines.append("")
    lines.append("Generated by `scripts/migration_map.py` from `catalog/services/catalog.yaml`. Do not edit by hand.")
    lines.append("")
    lines.append(
        "Every routed service, the domain that owns it, the crate it answers from, the address the gateway "
        "publishes it on, whether it owns records, and what retires its Python directory."
    )
    lines.append("")
    lines.append(f"- Routed services: {len(services)}")
    lines.append(f"- Answering from a Rust crate: {len(on_rust)}")
    lines.append(f"- Still answering from Python: {len(on_python)}")
    lines.append(f"- Domains: {len(domains)}")
    lines.append("")
    lines.append("## Ownership rules this map is held to")
    lines.append("")
    lines.append(
        "1. One crate per business domain. A service never gets a crate of its own when a domain crate already exists."
    )
    lines.append(
        "2. `ledger-core` stays the sole authority for posting integrity, immutability, reversal rules and the hash "
        "chain. No domain crate posts its own ledger."
    )
    lines.append("3. A module never creates another module's authoritative source of truth.")
    lines.append("4. Each gateway path is registered once, by one service.")
    lines.append("5. No fixed semantic limits on accounts, users, organisations, volumes or providers.")
    lines.append("")

    for name in sorted(domains):
        domain = domains[name]
        held = [service for service in services if service["domain"] == name]
        if not held:
            continue
        done = sum(1 for service in held if service["engine"] == "rust")
        lines.append(f"## {name} — {done}/{len(held)} on Rust")
        lines.append("")
        lines.append(f"*Responsibility:* {domain['responsibility']}")
        lines.append("")
        lines.append(f"*Destination:* `{domain['target']}`")
        lines.append("")
        lines.append("```text")
        lines.append(f"{'service':44} {'address':34} {'eps':>3}  {'owns':4} {'engine':6} crate")
        for service in sorted(held, key=lambda one: one["name"]):
            address = service.get("gateway_path") or "-"
            owns = "recs" if service.get("records") else "-"
            lines.append(
                f"{service['name']:44} {address:34} {len(service.get('endpoints', [])):>3}  "
                f"{owns:4} {service['engine']:6} {service['target']}"
            )
        lines.append("```")
        lines.append("")
        lines.append("| service | proof today | retires when |")
        lines.append("| --- | --- | --- |")
        for service in sorted(held, key=lambda one: one["name"]):
            lines.append(
                f"| `{service['name']}` | {PROOF[service['engine']]} | "
                f"{gate(service['engine'], bool(service.get('records')))} |"
            )
        lines.append("")

    lines.append("## What is left")
    lines.append("")
    if on_python:
        for position, service in enumerate(sorted(on_python, key=lambda one: one["name"]), start=1):
            lines.append(
                f"{position}. `{service['name']}` — {len(service.get('endpoints', []))} endpoints, "
                f"{'owns records' if service.get('records') else 'no records'}, "
                f"goes to `{service['target']}`"
            )
    else:
        lines.append("Nothing. Every routed service answers from a Rust crate.")
    lines.append("")
    lines.append("## Completion gates")
    lines.append("")
    lines.append("A ported service is not finished until all of these hold:")
    lines.append("")
    lines.append("1. Each fixed path in the Python service has exactly one route registered in the API server.")
    lines.append("2. The crate's own tests cover the calculators, and an HTTP route test covers the surface.")
    lines.append("3. Record shapes and Book scoping match, so a caller cannot see another Book's rows.")
    lines.append(
        "4. `./scripts/preflight.sh` is clean: formatting, clippy at deny warnings, workspace tests, the Python"
    )
    lines.append("   extension build, lint and pytest, and the seam parity checks.")
    lines.append("5. The port tracker, the catalogue and this map all name the service as ported.")
    lines.append("")

    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(on_rust)} on rust, {len(on_python)} python, {len(domains)} domains")


if __name__ == "__main__":
    main()
