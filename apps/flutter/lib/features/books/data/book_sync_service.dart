  // -- crypto ------------------------------------------------------------

  /// Random 256-bit AES book key, base64-encoded.
  String generateBookKey() {
    final rnd = FortunaRandom();
    final seed = Uint8List.fromList(
      List<int>.generate(32, (_) => Random.secure().nextInt(256)),
    );
    rnd.seed(KeyParameter(seed));
    final key = rnd.nextBytes(32);
    return base64Encode(key);
  }

  Uint8List _aesKey(String bookKeyB64) =>
      Uint8List.fromList(base64Decode(bookKeyB64));

  /// The four bytes that mark a payload as carrying its own nonce.
  ///
  /// A GCM nonce must never repeat under one key, and the first version of this file used a fixed nonce of twelve zero
  /// bytes for every payload written under a Book key. Reuse of a GCM nonce is not a weakness that degrades: it hands an
  /// observer the exclusive-or of two plaintexts and the material to forge the tag, so every payload a Book ever held
  /// shared one keystream. New payloads carry a fresh random nonce in front of the ciphertext under this marker, and a
  /// payload without the marker is read the old way so that Books written before the change still open.
  static const List<int> _nonceEnvelope = [0x56, 0x4D, 0x42, 0x31]; // "VMB1"
  static const int _nonceBytes = 12;

  /// AES-256-GCM with the constant-time AES core, not the T-table one.
  ///
  /// `AESFastEngine` is the table-driven variant and is deprecated upstream because table lookups leak key material to a
  /// side channel; a Book key lives on a phone with other apps on it, so the slower core is the right trade.
  GCMBlockCipher _gcm({
    required bool forEncryption,
    required String bookKeyB64,
    required Uint8List nonce,
  }) => GCMBlockCipher(AESEngine())
    ..init(
      forEncryption,
      AEADParameters(
        KeyParameter(_aesKey(bookKeyB64)),
        128,
        nonce,
        Uint8List(0),
      ),
    );

  Uint8List _freshNonce() => Uint8List.fromList(
    List<int>.generate(_nonceBytes, (_) => Random.secure().nextInt(256)),
  );

  /// AES-256-GCM encrypt a JSON payload with the Book key, under a nonce nobody has used before.
  String encryptPayload(String bookKeyB64, Map<String, dynamic> data) {
    final nonce = _freshNonce();
    final plain = Uint8List.fromList(utf8.encode(jsonEncode(data)));
    final sealed = _gcm(
      forEncryption: true,
      bookKeyB64: bookKeyB64,
      nonce: nonce,
    ).process(plain);
    return base64Encode([..._nonceEnvelope, ...nonce, ...sealed]);
  }

  /// Decrypt a payload fetched from the sync server, in either the marked form or the old fixed-nonce one.
  Map<String, dynamic> decryptPayload(String bookKeyB64, String b64) {
    final body = Uint8List.fromList(base64Decode(b64));
    var marked = body.length > _nonceEnvelope.length + _nonceBytes;
    for (var i = 0; marked && i < _nonceEnvelope.length; i++) {
      marked = body[i] == _nonceEnvelope[i];
    }
    final nonce = marked
        ? Uint8List.sublistView(
            body,
            _nonceEnvelope.length,
            _nonceEnvelope.length + _nonceBytes,
          )
        : Uint8List(_nonceBytes);
    final sealed = marked
        ? Uint8List.sublistView(body, _nonceEnvelope.length + _nonceBytes)
        : body;
    final clear = _gcm(
      forEncryption: false,
      bookKeyB64: bookKeyB64,
      nonce: Uint8List.fromList(nonce),
    ).process(Uint8List.fromList(sealed));
    return jsonDecode(utf8.decode(clear)) as Map<String, dynamic>;
  }

  // -- books -------------------------------------------------------------

  Future<List<VBook>> refreshBooksFromServer() async {
    final r = await _client.get(_u('/books'), headers: _headers);
    if (r.statusCode != 200) {
      throw Exception('Failed to load books: ${r.statusCode}');
    }
    // opening Books is the moment this phone becomes reachable: without a published key nobody can invite you, and
    // waiting until you create a Book of your own meant a brand-new person could never be put into anyone's Book.
    await _publishOnce();
    final books =
        (jsonDecode(r.body) as Map<String, dynamic>)['books'] as List<dynamic>;
    final meta = await _meta();
    final List<VBook> result = [];
    for (final b in books) {
      final book = VBook.fromJson(b as Map<String, dynamic>);
      await meta.insert('registry', {
        'book_id': book.id,
        'name': book.name,
        'tier': book.tier,
        'description': book.description,
        'folder': book.folder,
        'role': book.yourRole,
        'status': book.membershipStatus,
        'last_meta_sync': DateTime.now().millisecondsSinceEpoch / 1000.0,
      }, conflictAlgorithm: ConflictAlgorithm.replace);
      result.add(book);
    }
    // A Book this phone joined but cannot open is worth one quiet attempt to repair: the key is already this person's - they
    // are in the Book - and asking for it is the only thing that turns a membership into something readable. Without this the
    // phone would show a joined Book that stays empty until somebody else sends a new invitation.
    for (final book in result) {
      if (book.membershipStatus == 'active') {
        await _collectKeyIfMissing(book.id);
      }
    }
    return result;
  }

  /// Ask the engine for this person's copy of a Book key, and keep it if it opens.
  ///
  /// Silent by design: a Book that still cannot be opened is a Book this person was told about already, and a refresh is not
  /// the moment to raise it again. The one thing that must not happen is a wrong key being stored as if it worked.
  Future<bool> _collectKeyIfMissing(String bookId) async {
    final held = await bookKeyFor(bookId);
    if (held.isNotEmpty) return true;
    try {
      final r = await _client.get(_u('/books/$bookId/key'), headers: _headers);
      if (r.statusCode != 200) return false;
      final wrapped =
          (jsonDecode(r.body) as Map<String, dynamic>)['wrapped_book_key']
              as String? ??
          '';
      if (wrapped.isEmpty) return false;
      final bookKey = await unwrapBookKey(wrapped);
      if (bookKey.isEmpty) return false;
      final meta = await _meta();
      await meta.update(
        'registry',
        {'book_key': bookKey},
        where: 'book_id = ?',
        whereArgs: [bookId],
      );
      return true;
    } catch (_) {
      // a key that will not open is not stored, and not reported here: the Book list already says the Book is joined
      return false;
    }
  }

  Future<List<VBook>> localBooks() async {
    final meta = await _meta();
    final rows = await meta.query('registry');
    return rows.map((r) {
      return VBook(
        id: r['book_id'] as String,
        name: r['name'] as String,
        tier: r['tier'] as String,
        description: r['description'] as String? ?? '',
        folder: r['folder'] as String? ?? '',
        yourRole: r['role'] as String? ?? 'viewer',
        membershipStatus: r['status'] as String? ?? 'active',
        seq: (r['local_seq'] as num?)?.toInt() ?? 0,
      );
    }).toList();
  }

  /// Create a Book. For shared tiers (household/group/business) a fresh
  /// AES-256 Book key is generated on-device; the server only receives
  /// the key wrapped for *you* via your RSA public key, so it stays
  /// end-to-end encrypted even in transit.
  Future<VBook> createBook(
    String name,
    String tier, {
    String description = '',
    String folder = '',
  }) async {
    final bookKey = generateBookKey();
    try {
      await publishDevicePublicKey();
    } catch (_) {
      // a Book that cannot be shared yet is still a working Book; sharing offers to publish again
    }
    final wrapped = await wrapBookKeyForSelf(bookKey);
    final r = await _client.post(
      _u('/books'),
      headers: _headers,
      body: jsonEncode({
        'name': name,
        'tier': tier,
        'description': description,
        'folder': folder,
        'wrapped_book_key': wrapped,
      }),
    );
    if (r.statusCode != 200) {
      throw Exception('Create book failed: ${r.statusCode} ${r.body}');
    }
    final j = jsonDecode(r.body) as Map<String, dynamic>;
    final book = VBook.fromJson(
      j['book'] as Map<String, dynamic>,
    ).copyWithKeyInfo(bookKey);
    final meta = await _meta();
    await meta.insert('registry', {
      'book_id': book.id,
      'name': book.name,
      'tier': book.tier,
      'description': book.description,
      'folder': book.folder,
      'role': 'owner',
      'status': 'active',
      'book_key': bookKey,
      'device_id': '',
      'local_seq': 0,
      'last_meta_sync': DateTime.now().millisecondsSinceEpoch / 1000.0,
    }, conflictAlgorithm: ConflictAlgorithm.replace);
    await _ensureDevice(book.id);
    return book;
  }

  // -- device key pair ---------------------------------------------------

  static String _b64(BigInt value) => base64Encode(_unsignedBytes(value));

  static List<int> _unsignedBytes(BigInt value) {
    final bytes = <int>[];
    var rest = value;
    while (rest > BigInt.zero) {
      bytes.insert(0, (rest & BigInt.from(0xFF)).toInt());
      rest = rest >> 8;
    }
    return bytes.isEmpty ? [0] : bytes;
  }

  static BigInt _fromB64(String b64) {
    var value = BigInt.zero;
    for (final byte in base64Decode(b64)) {
      value = (value << 8) | BigInt.from(byte);
    }
    return value;
  }

  RSAKeyPairHolder? _deviceKeys;

  /// The device's own RSA key pair, made once and kept on this phone.
  ///
  /// A Book key must reach another member without the server ever holding it in a form it can read, which needs a key
  /// pair belonging to the device. It is generated on first use and stored beside the Book registry; the private half
  /// never leaves the phone.
  Future<RSAKeyPairHolder> _deviceKeyPair() async {
    if (_deviceKeys != null) return _deviceKeys!;
    final db = await _meta();
    final rows = await db.query('device_key', where: 'id = 1', limit: 1);
    if (rows.isEmpty) {
      final generator = RSAKeyGenerator()
        ..init(
          ParametersWithRandom(
            RSAKeyGeneratorParameters(BigInt.from(65537), 2048, 64),
            _secureRandom(),
          ),
        );
      final pair = generator.generateKeyPair();
      final pub = pair.publicKey as RSAPublicKey;
      final priv = pair.privateKey as RSAPrivateKey;
      await db.insert('device_key', {
        'id': 1,
        'modulus': _b64(pub.modulus!),
        'exponent': _b64(pub.exponent!),
        'private_exponent': _b64(priv.privateExponent!),
        'prime_p': priv.p == null ? null : _b64(priv.p!),
        'prime_q': priv.q == null ? null : _b64(priv.q!),
      }, conflictAlgorithm: ConflictAlgorithm.replace);
      _deviceKeys = RSAKeyPairHolder(pub, priv);
      return _deviceKeys!;
    }
    final row = rows.first;
    final n = _fromB64(row['modulus'] as String);
    final e = _fromB64(row['exponent'] as String);
    final d = _fromB64(row['private_exponent'] as String);
    final pp = row['prime_p'] as String?;
    final qq = row['prime_q'] as String?;
    _deviceKeys = RSAKeyPairHolder(
      RSAPublicKey(n, e),
      RSAPrivateKey(
        n,
        d,
        pp == null ? null : _fromB64(pp),
        qq == null ? null : _fromB64(qq),
      ),
    );
    return _deviceKeys!;
  }

  SecureRandom _secureRandom() {
    final seed = Uint8List.fromList(
      List<int>.generate(32, (_) => Random.secure().nextInt(256)),
    );
    return FortunaRandom()..seed(KeyParameter(seed));
  }

  Uint8List _oaep(
    bool forEncryption,
    AsymmetricKeyParameter key,
    Uint8List input,
  ) {
    final engine = OAEPEncoding(RSAEngine())..init(forEncryption, key);
    return engine.process(input);
  }

  bool _publishedThisSession = false;

  /// Forget that this key was published, so a test can watch a first visit again. Nothing in the app calls it.
  void forgetPublishedKey() => _publishedThisSession = false;

  /// Publish the key once per session, quietly. Every phone that opens a Book list should be somebody an invitation can
  /// reach, not only a phone that happens to own a Book already.
  Future<void> _publishOnce() async {
    if (_publishedThisSession) return;
    try {
      _publishedThisSession = await publishDevicePublicKey();
    } catch (_) {
      // the engine being unreachable must not stop the list from loading; the next visit tries again
    }
  }

  /// Publish this device's public key so another person can wrap a Book key for it.
  ///
  /// The public half is what an inviter fetches, so it has to exist before anybody can put you in a Book. Failure is not
  /// fatal here: a Book that cannot be shared is still a working Book, and the shell that offers sharing says so.
  Future<bool> publishDevicePublicKey() async {
    final keys = await _deviceKeyPair();
    final r = await _client.put(
      Uri.parse('${AppConfig.apiUrl}/identity/users/me/public-key'),
      headers: {..._headers, 'Content-Type': 'application/json'},
      body: jsonEncode({
        'modulus': _b64(keys.publicKey.modulus!),
        'exponent': _b64(keys.publicKey.exponent!),
      }),
    );
    return r.statusCode == 200;
  }

  /// Find a person by username or email, so an invitation can name somebody instead of asking for an internal id.
  ///
  /// Returns null when no active account has that name, which the shell shows as "no account called that" rather than as
  /// a failure: a mistyped name is not a broken engine.
  Future<Map<String, dynamic>?> findPerson(String usernameOrEmail) async {
    final name = usernameOrEmail.trim();
    if (name.isEmpty) return null;
    final r = await _client.get(
      Uri.parse(
        '${AppConfig.apiUrl}/identity/users/lookup?username=${Uri.encodeQueryComponent(name)}',
      ),
      headers: _headers,
    );
    if (r.statusCode == 404) return null;
    if (r.statusCode != 200) {
      throw Exception('Could not look that name up: ${r.statusCode} ${r.body}');
    }
    return jsonDecode(r.body) as Map<String, dynamic>;
  }

  /// Invite by the name a person already knows, resolving it here so the caller passes a username rather than an id.
  Future<Map<String, dynamic>> inviteMemberByUsername(
    String bookId,
    String usernameOrEmail,
    String role,
  ) async {
    final person = await findPerson(usernameOrEmail);
    if (person == null) {
      throw Exception('No active account is called "$usernameOrEmail".');
    }
    await inviteMember(bookId, person['id'] as String, role);
    return person;
  }

  /// Another person's public key, fetched so a Book key can be wrapped for them.
  Future<RSAPublicKey> fetchPublicKey(String userId) async {
    final r = await _client.get(
      Uri.parse('${AppConfig.apiUrl}/identity/users/$userId/public-key'),
      headers: _headers,
    );
    if (r.statusCode == 404) {
      throw Exception(
        'That person has not opened Vimbai on a phone yet, so there is no key to wrap the Book key for.',
      );
    }
    if (r.statusCode != 200) {
      throw Exception(
        'Could not read their public key: ${r.statusCode} ${r.body}',
      );
    }
    final j = jsonDecode(r.body) as Map<String, dynamic>;
    return RSAPublicKey(
      _fromB64(j['modulus'] as String),
      _fromB64(j['exponent'] as String),
    );
  }

  /// Wrap a Book key for somebody else's public key.
  Future<String> wrapBookKeyFor(String userId, String bookKey) async {
    final theirKey = await fetchPublicKey(userId);
    final sealed = _oaep(
      true,
      PublicKeyParameter<RSAPublicKey>(theirKey),
      Uint8List.fromList(utf8.encode(bookKey)),
    );
    return base64Encode(sealed);
  }

  /// The Book key this phone holds for a Book, or '' when it holds none.
  Future<String> bookKeyFor(String bookId) async {
    final meta = await _meta();
    final rows = await meta.query(
      'registry',
      where: 'book_id = ?',
      whereArgs: [bookId],
      limit: 1,
    );
    if (rows.isEmpty) return '';
    return rows.first['book_key'] as String? ?? '';
  }

  /// Wrap a Book key for this device's own public key.
  Future<String> wrapBookKeyForSelf(String bookKey) async {
    final keys = await _deviceKeyPair();
    final sealed = _oaep(
      true,
      PublicKeyParameter<RSAPublicKey>(keys.publicKey),
      Uint8List.fromList(utf8.encode(bookKey)),
    );
    return base64Encode(sealed);
  }

  /// Open a Book key that was wrapped for this device.
  ///
  /// A key wrapped by the first version of this file carries the plaintext key base64-encoded behind a `self:` mark; it is
  /// still read so Books created before the device had a key pair keep opening.
  Future<String> unwrapBookKey(String wrapped) async {
    if (wrapped.startsWith('self:')) {
      return utf8.decode(base64Decode(wrapped.substring('self:'.length)));
    }
    final keys = await _deviceKeyPair();
    final clear = _oaep(
      false,
      PrivateKeyParameter<RSAPrivateKey>(keys.privateKey),
      Uint8List.fromList(base64Decode(wrapped)),
    );
    return utf8.decode(clear);
  }

  /// Update a Book (name/description/folder). Folder moves keep the Book in
  /// the chosen client-side folder; pass '' to unfile it. Requires owner or
  /// admin membership server-side.
  Future<void> updateBook(
    String bookId, {
    String? name,
    String? description,
    String? folder,
  }) async {
    final body = <String, dynamic>{};
    if (name != null) body['name'] = name;
    if (description != null) body['description'] = description;
    if (folder != null) body['folder'] = folder.trim();
    final r = await _client.put(
      _u('/books/$bookId'),
      headers: _headers,
      body: jsonEncode(body),
    );
    if (r.statusCode != 200) {
      throw Exception('Update book failed: ${r.statusCode} ${r.body}');
    }
    // keep the local registry in sync so folder grouping survives offline
    final meta = await _meta();
    final patch = <String, dynamic>{};
    if (name != null) patch['name'] = name;
    if (description != null) patch['description'] = description;
    if (folder != null) patch['folder'] = folder.trim();
    if (patch.isNotEmpty) {
      patch['book_id'] = bookId;
      await meta.update(
        'registry',
        patch,
        where: 'book_id = ?',
        whereArgs: [bookId],
      );
    }
  }

  Future<void> _ensureDevice(String bookId) async {
    final meta = await _meta();
    final rows = await meta.query(
      'registry',
      where: 'book_id = ?',
      whereArgs: [bookId],
      limit: 1,
    );
    if (rows.isEmpty) return;
    if ((rows.first['device_id'] as String? ?? '').isNotEmpty) return;
    final r = await _client.post(
      _u('/books/$bookId/devices'),
      headers: _headers,
      body: jsonEncode({'device_name': Platform.operatingSystem}),
    );
    if (r.statusCode == 200) {
      final deviceId =
          (jsonDecode(r.body) as Map<String, dynamic>)['device_id'] as String;
      await meta.update(
        'registry',
        {'device_id': deviceId},
        where: 'book_id = ?',
        whereArgs: [bookId],
      );
    }
  }

  /// Accept a pending invitation; stores the wrapped key copy we get back.
  Future<void> acceptInvite(String bookId) async {
    final r = await _client.post(
      _u('/books/$bookId/members/accept'),
      headers: _headers,
    );
    if (r.statusCode != 200) {
      throw Exception('Accept failed: ${r.statusCode} ${r.body}');
    }
    final j = jsonDecode(r.body) as Map<String, dynamic>;
    // the key arrives wrapped for this device, so it is opened here and never stored in a form the server could read
    final wrapped = j['wrapped_book_key'] as String? ?? '';
    final meta = await _meta();
    if (wrapped.isEmpty) {
      // joined, but nothing to open: the membership is real on the server, so the phone must not stay "invited" and
      // pretend a second tap will fix it. It says so instead, and the owner has to invite this device again.
      await meta.update(
        'registry',
        {'status': 'active', 'book_key': ''},
        where: 'book_id = ?',
        whereArgs: [bookId],
      );
      throw const BookKeyUnavailableException(
        'You joined this Book, but the invitation brought no key for this phone, so nothing in it can be read here. '
        'Ask whoever shared it to invite you again.',
      );
    }
    final String bookKey;
    try {
      bookKey = await unwrapBookKey(wrapped);
    } catch (failure) {
      // the key was sealed for another device - an invitation made before this phone had a key, for instance. The
      // membership is already active, so the Book is recorded as joined-and-unreadable rather than left looking
      // acceptable, and the person is told the one thing that fixes it.
      await meta.update(
        'registry',
        {'status': 'active', 'book_key': ''},
        where: 'book_id = ?',
        whereArgs: [bookId],
      );
      print(
        'Accepting $bookId: the wrapped key could not be opened ($failure).',
      );
      throw const BookKeyUnavailableException(
        'You joined this Book, but its key was sealed for a different device, so nothing in it can be read here. '
        'Ask whoever shared it to send the invitation again now that this phone has its own key.',
      );
    }
    await meta.update(
      'registry',
      {'status': 'active', 'book_key': bookKey},
      where: 'book_id = ?',
      whereArgs: [bookId],
    );
  }

  /// Invite someone into a Book, wrapping the Book key for their key on the way out.
  ///
  /// The wrapped key used to be the text `wrapped:<user id>`, which is not a key at all: the engine accepted it and the
  /// person joined and could read nothing. The wrap happens here now, so an invitation that leaves this phone is one the
  /// invitee can actually open - and one the server cannot.
  Future<void> inviteMember(String bookId, String userId, String role) async {
    final bookKey = await bookKeyFor(bookId);
    if (bookKey.isEmpty) {
      throw Exception(
        'This Book has no key on this phone, so it cannot be shared from here.',
      );
    }
    final wrapped = await wrapBookKeyFor(userId, bookKey);
    final r = await _client.post(
      _u('/books/$bookId/members'),
      headers: {..._headers, 'Content-Type': 'application/json'},
      body: jsonEncode({
        'user_id': userId,
        'role': role,
        'wrapped_book_key': wrapped,
      }),
    );
    if (r.statusCode != 200) {
      throw Exception('Invite failed: ${r.statusCode} ${r.body}');
    }
  }

  /// What has happened in a Book, newest first, as the engine recorded it.
  ///
  /// A shared Book is kept by more than one person, and "who changed this" is the question an owner asks the moment the
  /// numbers move in a way they did not expect. The engine has kept this record all along - invitations, acceptances, devices,
  /// pushed batches - and nothing surfaced it.
  Future<List<Map<String, dynamic>>> activity(String bookId) async {
    final r = await _client.get(_u('/books/$bookId/audit'), headers: _headers);
    if (r.statusCode != 200) {
      throw Exception('Activity failed: ${r.statusCode}');
    }
    final rows =
        (jsonDecode(r.body) as Map<String, dynamic>)['audit'] as List<dynamic>;
    return rows.cast<Map<String, dynamic>>();
  }

  /// Change a member's role, or take them out of the Book, and say what changed.
  ///
  /// Revoking is how sharing is undone: the person keeps whatever they already pulled, but the Book stops answering them and
  /// nothing they post lands in it. The engine refuses to touch the owner by this door, so a Book cannot be left with nobody
  /// who can administer it.
  Future<void> updateMember(
    String bookId,
    String userId, {
    String? role,
    String? status,
  }) async {
    final body = <String, dynamic>{};
    if (role != null) body['role'] = role;
    if (status != null) body['status'] = status;
    if (body.isEmpty) return;
    final r = await _client.put(
      _u('/books/$bookId/members/$userId'),
      headers: {..._headers, 'Content-Type': 'application/json'},
      body: jsonEncode(body),
    );
    if (r.statusCode != 200) {
      throw Exception('Change member failed: ${r.statusCode} ${r.body}');
    }
  }

  Future<List<BookMember>> members(String bookId) async {
    final r = await _client.get(
      _u('/books/$bookId/members'),
      headers: _headers,
    );
    if (r.statusCode != 200) {
      throw Exception('Members failed: ${r.statusCode}');
    }
    final ms =
        (jsonDecode(r.body) as Map<String, dynamic>)['members']
            as List<dynamic>;
    return ms
        .map((m) => BookMember.fromJson(m as Map<String, dynamic>))
        .toList();
  }

  // -- entry sync --------------------------------------------------------

  /// Queue a JSON record into a Book's encrypted outbox. Personal Books
  /// simply persist locally; nothing leaves the device.
  Future<String> enqueueEntry(
    String bookId,
    Map<String, dynamic> data, {
    bool shared = true,
  }) async {
    final db = await _bookDb(bookId);
    final meta = await _meta();
    final rows = await meta.query(
      'registry',
      where: 'book_id = ?',
      whereArgs: [bookId],
      limit: 1,
    );
    final row = rows.first;
    final bookKey = row['book_key'] as String? ?? '';
    final entryId = _uuid.v4();
    final ciphertext = bookKey.isEmpty
        ? base64Encode(utf8.encode(jsonEncode(data)))
        : encryptPayload(bookKey, data);
    await db.insert('entries', {
      'entry_id': entryId,
      'seq': null,
      'user_id': '',
      'created_at': DateTime.now().millisecondsSinceEpoch / 1000.0,
      'ciphertext': ciphertext,
      'pending': shared ? 1 : 0,
    });
    return entryId;
  }

  /// Push all pending entries for a Book, then pull everything new.
  /// Returns (pushed, pulled).
  Future<Map<String, int>> syncBook(String bookId) async {
    final meta = await _meta();
    final rows = await meta.query(
      'registry',
      where: 'book_id = ?',
      whereArgs: [bookId],
      limit: 1,
    );
    if (rows.isEmpty) throw Exception('Unknown book');
    final row = rows.first;
    final deviceId = row['device_id'] as String? ?? '';
    final localSeq = (row['local_seq'] as num?)?.toInt() ?? 0;
    if (deviceId.isEmpty) {
      await _ensureDevice(bookId);
      return syncBook(bookId);
    }
    final db = await _bookDb(bookId);

    // 1. Push pending
    final pending = await db.query('entries', where: 'pending = 1', limit: 100);
    var pushed = 0;
    if (pending.isNotEmpty) {
      final body = {
        'device_id': deviceId,
        'entries': pending
            .map(
              (e) => {
                'entry_id': e['entry_id'],
                'payload': e['ciphertext'],
                'created_at': e['created_at'],
              },
            )
            .toList(),
      };
      final r = await _client.post(
        _u('/books/$bookId/entries/push'),
        headers: _headers,
        body: jsonEncode(body),
      );
      if (r.statusCode != 200) {
        throw Exception('Push failed: ${r.statusCode} ${r.body}');
      }
      final serverSeq =
          (jsonDecode(r.body) as Map<String, dynamic>)['book_seq'] as int;
      for (final e in pending) {
        await db.update(
          'entries',
          {'pending': 0, 'seq': serverSeq},
          where: 'entry_id = ?',
          whereArgs: [e['entry_id']],
        );
      }
      pushed = pending.length;
    }

    // 2. Pull deltas
    final r = await _client.get(
      _u('/books/$bookId/entries', {'since': '$localSeq', 'limit': '500'}),
      headers: _headers,
    );
    if (r.statusCode != 200) {
      throw Exception('Pull failed: ${r.statusCode}');
    }
    final j = jsonDecode(r.body) as Map<String, dynamic>;
    var pulled = 0;
    for (final e in (j['entries'] as List<dynamic>)) {
      final em = e as Map<String, dynamic>;
      final existing = await db.query(
        'entries',
        where: 'entry_id = ?',
        whereArgs: [em['entry_id']],
        limit: 1,
      );
      if (existing.isNotEmpty) {
        await db.update(
          'entries',
          {'seq': em['seq'], 'pending': 0},
          where: 'entry_id = ?',
          whereArgs: [em['entry_id']],
        );
        continue;
      }
      await db.insert('entries', {
        'entry_id': em['entry_id'],
        'seq': em['seq'],
        'user_id': em['user_id'],
        'created_at': em['created_at'],
        'ciphertext': em['payload'],
        'pending': 0,
      }, conflictAlgorithm: ConflictAlgorithm.replace);
      pulled++;
    }
    final bookSeq = j['book_seq'] as int;
    await meta.update(
      'registry',
      {'local_seq': bookSeq},
      where: 'book_id = ?',
      whereArgs: [bookId],
    );
    return {'pushed': pushed, 'pulled': pulled};
  }

  /// Sync every active shared Book (used by the periodic cycle).
  Future<Map<String, Map<String, int>>> syncAllSharedBooks() async {
    final books = await localBooks();
    final results = <String, Map<String, int>>{};
    for (final b in books) {
      if (b.tier == 'personal') continue;
      if (b.membershipStatus != 'active') continue;
      if (!kBookWriterRoles.contains(b.yourRole)) {
        // viewers/auditors still pull
      }
      try {
        results[b.id] = await syncBook(b.id);
      } catch (_) {
        // offline - next cycle retries; entries stay safely queued
      }
    }
    return results;
  }

  /// Decrypt and return all local entries of a Book (for UI/reporting).
  Future<List<Map<String, dynamic>>> readEntries(String bookId) async {
    final db = await _bookDb(bookId);
    final meta = await _meta();
    final rows = await meta.query(
      'registry',
      where: 'book_id = ?',
      whereArgs: [bookId],
      limit: 1,
    );
    if (rows.isEmpty) return [];
    final bookKey = rows.first['book_key'] as String? ?? '';
    final entries = await db.query('entries', orderBy: 'created_at ASC');
    return entries.map((e) {
      final ct = e['ciphertext'] as String;
      Map<String, dynamic> data;
      if (bookKey.isEmpty || ct.startsWith('self:')) {
        data =
            jsonDecode(utf8.decode(base64Decode(ct))) as Map<String, dynamic>;
      } else {
        data = decryptPayload(bookKey, ct);
      }
      return {
        'entry_id': e['entry_id'],
        'seq': e['seq'],
        'pending': e['pending'] == 1,
        'data': data,
      };
    }).toList();
  }

  void dispose() {
    // the connection itself belongs to the app's shared client, which outlives this service
    for (final db in _bookDbs.values) {
      db.close();
    }
    _bookDbs.clear();
  }
}

