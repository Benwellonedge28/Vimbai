/// An invitation that was accepted but left this phone unable to read the Book.
///
/// Its text is a sentence for a person, so a screen can show it as it stands: the difference between "the server said no"
/// and "you are in, but this device cannot open it" is the whole difference between trying again and asking the owner.
class BookKeyUnavailableException implements Exception {
  const BookKeyUnavailableException(this.message);
  final String message;
  @override
  String toString() => message;
}

class BookSyncService {
  BookSyncService._();
  static final BookSyncService instance = BookSyncService._();

  /// A second instance over the same engine, for a test that needs two phones. Nothing in the app builds one.
  BookSyncService.secondPhone();

  // Route through the API gateway so the JWT is resolved to X-User-ID.
  static const String _kBaseUrl = String.fromEnvironment(
    'VIMBAI_BOOK_SYNC_URL',
    defaultValue: '${AppConfig.apiUrl}/book-sync',
  );

  // Every Book call goes through the app's own client, so an unreachable engine becomes the app's typed offline failure
  // with the standard timeout rather than a raw socket error from a second, separately-behaved connection.
  final ApiClient _client = ApiClient();
  String? _authToken;

  final Uuid _uuid = const Uuid();
  Database? _metaDb; // book registry + keys
  final Map<String, Database> _bookDbs = {};

  // -- registry ----------------------------------------------------------

  /// Where the local stores live. A test points this at its own directory.
  ///
  /// Both stores used to sit in one shared directory, so two test files running at once opened the same database file and
  /// fought over its locks. Nothing in the app sets it.
  static String? databasesDirectory;

  Future<String> _databaseDirectory() async =>
      databasesDirectory ?? await getDatabasesPath();

  Future<Database> _meta() async {
    if (_metaDb != null) return _metaDb!;
    final dir = await _databaseDirectory();
    _metaDb = await openDatabase(
      p.join(dir, 'vimbai_books.db'),
      version: 3,
      onCreate: (db, _) async {
        await db.execute('''
          CREATE TABLE device_key (
            id INTEGER PRIMARY KEY CHECK (id = 1),
            modulus TEXT NOT NULL,
            exponent TEXT NOT NULL,
            private_exponent TEXT NOT NULL,
            prime_p TEXT,
            prime_q TEXT
          )
        ''');
        await db.execute('''
          CREATE TABLE registry (
            book_id TEXT PRIMARY KEY,
            name TEXT NOT NULL,
            tier TEXT NOT NULL,
            description TEXT DEFAULT '',
            folder TEXT DEFAULT '',
            role TEXT NOT NULL,
            status TEXT NOT NULL,
            local_seq INTEGER NOT NULL DEFAULT 0,
            device_id TEXT DEFAULT '',
            book_key TEXT DEFAULT '',
            last_meta_sync REAL NOT NULL DEFAULT 0
          )
        ''');
      },
      onUpgrade: (db, oldVersion, newVersion) async {
        if (oldVersion < 3) {
          // v3: the device holds its own key pair, so a Book key leaves this phone wrapped for it
          await db.execute('''
            CREATE TABLE IF NOT EXISTS device_key (
              id INTEGER PRIMARY KEY CHECK (id = 1),
              modulus TEXT NOT NULL,
              exponent TEXT NOT NULL,
              private_exponent TEXT NOT NULL,
              prime_p TEXT,
              prime_q TEXT
            )
          ''');
        }
        if (oldVersion < 2) {
          // v2: Books can be organized into folders.
          await db.execute(
            "ALTER TABLE registry ADD COLUMN folder TEXT DEFAULT ''",
          );
        }
      },
    );
    return _metaDb!;
  }

  Future<Database> _bookDb(String bookId) async {
    if (_bookDbs.containsKey(bookId)) return _bookDbs[bookId]!;
    final dir = await _databaseDirectory();
    final db = await openDatabase(
      p.join(dir, 'vimbai_book_$bookId.db'),
      version: 1,
      onCreate: (d, _) async {
        await d.execute('''
          CREATE TABLE entries (
            entry_id TEXT PRIMARY KEY,
            seq INTEGER,
            user_id TEXT,
            created_at REAL NOT NULL,
            ciphertext TEXT NOT NULL,
            pending INTEGER NOT NULL DEFAULT 0
          )
        ''');
        await d.execute('''
          CREATE TABLE meta (
            key TEXT PRIMARY KEY,
            value TEXT NOT NULL,
            updated_at REAL NOT NULL
          )
        ''');
      },
    );
    _bookDbs[bookId] = db;
    return db;
  }

